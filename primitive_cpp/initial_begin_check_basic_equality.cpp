int सूचकमूल्यम्(wire* तारः, int विस्तारः) {
    for (int i = 0; i < विस्तारः; ++i) {
        char c = तारः[i].getVal();
        if (c == 'x' || c == 'X' || c == 'z' || c == 'Z') return -1;
    }
    int मूल्य = 0;
    for (int i = 0; i < विस्तारः && i < 31; ++i) {
        if (तारः[i].getVal() == '1') मूल्य |= (1 << i);
    }
    return मूल्य;
}
