std::string सर्वचरग्रहणम् (std::string मूल्यम्) {
    std::string सदारम्भचर = "";
    for (int क = 0; क < मूल्यम्.length(); क++) {
        if (मूल्यम्[क] != ' ') {
            सदारम्भचर = सदारम्भचर + " " + मूल्यम्[क];
        }
    }
    return सदारम्भचर;
}

