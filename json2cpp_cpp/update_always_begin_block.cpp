std::string नियुक्तचरस्वीकरणम् (std::string मूल्यम्) {
    std::string सदारम्भचर = "";
    for (int क = 0; क < मूल्यम्.length(); क++) {
        if (मूल्यम्[क] != ' ') {
            सदारम्भचर += मूल्यम्[क];
        } else  {
            break;
        }
    }
    return सदारम्भचर;
}

void चरपुनरावृत्तिनिवारणम् (std::vector<std::string>& शब्दनक्शा) {
    std::vector<std::string> शब्दनक्शाफलम्;
    std::unordered_set<std::string> पुनरावृत्तिशब्दनक्शा;
    for (const std::string& न : शब्दनक्शा) {
        if (पुनरावृत्तिशब्दनक्शा.find(न) == पुनरावृत्तिशब्दनक्शा.end()) {
            शब्दनक्शाफलम्.push_back(न);
            पुनरावृत्तिशब्दनक्शा.insert(न);
        }
    }
    शब्दनक्शा = std::move(शब्दनक्शाफलम्);
}

